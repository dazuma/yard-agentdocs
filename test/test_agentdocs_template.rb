# frozen_string_literal: true

require "helper"
require "tmpdir"

describe "agentdocs template" do
  let(:project_root) { ::File.expand_path("..", __dir__) }
  let(:example_doc_dir) { ::File.join(project_root, "example/doc") }

  # Runs from the project root so recorded source paths (used in "Defined in"
  # lines) come out relative, matching the example/doc fixtures.
  def generate(output_dir)
    ::YARD::Registry.clear
    ::Dir.chdir(project_root) do
      ::YARD::CLI::Yardoc.new.run(
        "--no-yardopts", "--no-save", "--no-stats", "--no-private",
        "-o", output_dir,
        "-t", "default",
        "-f", "agentdocs",
        "--title", "yard-agentdocs example — API Reference",
        "example/lib/geometry.rb",
        "example/lib/geometry/point.rb",
        "example/lib/geometry/computations.rb",
        "example/lib/geometry/shape.rb",
        "example/lib/geometry/polygon.rb",
        "example/lib/geometry/triangle.rb",
        "example/lib/geometry/circle.rb",
        "example/lib/geometry/vector.rb",
        "example/lib/stopwatch.rb"
      )
    end
  end

  # All regular file paths under +dir+, relative to +dir+, sorted for
  # deterministic diffing/output.
  def relative_files(dir)
    ::Dir.glob("**/*", base: dir).select { |rel_path| ::File.file?(::File.join(dir, rel_path)) }.sort
  end

  it "renders output identical to the example/doc fixture" do
    ::Dir.mktmpdir do |output_dir|
      generate(output_dir)

      actual_files = relative_files(output_dir)
      expected_files = relative_files(example_doc_dir)

      extra = actual_files - expected_files
      assert_empty(extra, "generated files not present under example/doc: #{extra.join(', ')}")

      missing = expected_files - actual_files
      assert_empty(missing, "example/doc files not generated by the template: #{missing.join(', ')}")

      (expected_files & actual_files).each do |rel_path|
        actual = ::File.read(::File.join(output_dir, rel_path))
        expected = ::File.read(::File.join(example_doc_dir, rel_path))
        assert_equal(expected, actual, "mismatch for #{rel_path}")
      end
    end
  end
end
